"""Pydantic models describing the structured script output.

These models are the contract between the generation engine, the API, and the
UI. Keeping the script strongly typed makes it easy for later stages of the
larger project (e.g. turning the script into audio) to consume reliable data.
"""

from __future__ import annotations

from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field


class GenreHint(str, Enum):
    """Optional high-level genre to steer tone. Free-form is also accepted."""

    drama = "drama"
    comedy = "comedy"
    thriller = "thriller"
    scifi = "sci-fi"
    fantasy = "fantasy"
    horror = "horror"
    romance = "romance"
    documentary = "documentary"
    adventure = "adventure"


# ---------- Request ----------

class GenerateRequest(BaseModel):
    """What the user submits."""

    prompt: str = Field(..., min_length=3, description="The user's story idea / prompt.")
    duration_minutes: Optional[float] = Field(
        default=None,
        gt=0,
        le=600,
        description="Target runtime in minutes. If omitted, the engine infers a sensible length.",
    )
    genre: Optional[str] = Field(
        default=None, description="Optional genre or tone hint (free text or a GenreHint value)."
    )
    language: str = Field(default="English", description="Language the script should be written in.")


# ---------- Script pieces ----------

class Character(BaseModel):
    name: str = Field(..., description="Character name.")
    role: str = Field(..., description="Role in the story, e.g. protagonist, antagonist, mentor.")
    description: str = Field(..., description="Who they are: background, appearance, personality.")
    motivation: str = Field(..., description="What this character wants / their driving goal.")
    emotional_arc: str = Field(
        ..., description="How the character's emotional state changes across the story."
    )
    voice_profile: str = Field(
        default="",
        description="Vocal traits (pitch, pace, accent, age) — useful for later text-to-speech stages.",
    )


class DialogueLine(BaseModel):
    character: str = Field(..., description="Name of the speaking character.")
    emotion: str = Field(..., description="Primary emotion driving the line, e.g. anxious, joyful.")
    line: str = Field(..., description="The spoken dialogue.")
    parenthetical: str = Field(
        default="", description="Optional acting/delivery note shown in parentheses (e.g. 'whispering')."
    )


class SceneElement(BaseModel):
    """A beat within a scene: either a direction/action or a dialogue line."""

    kind: str = Field(..., description="'action' for stage/scene direction, or 'dialogue'.")
    action: str = Field(default="", description="Scene direction / action text (when kind == 'action').")
    dialogue: Optional[DialogueLine] = Field(
        default=None, description="Dialogue line (when kind == 'dialogue')."
    )


class Scene(BaseModel):
    number: int = Field(..., description="Scene order, starting at 1.")
    heading: str = Field(..., description="Slugline, e.g. 'INT. KITCHEN - NIGHT'.")
    summary: str = Field(..., description="One-line summary of what happens in the scene.")
    mood: str = Field(..., description="Overall emotional atmosphere of the scene.")
    elements: List[SceneElement] = Field(
        default_factory=list, description="Ordered beats: actions and dialogue."
    )


class Script(BaseModel):
    title: str
    logline: str = Field(..., description="One-sentence summary of the whole story.")
    genre: str
    language: str
    estimated_duration_minutes: float = Field(
        ..., description="Engine's target/estimated runtime in minutes."
    )
    synopsis: str = Field(..., description="A short paragraph summarizing the full story.")
    characters: List[Character]
    scenes: List[Scene]


class GenerateResponse(BaseModel):
    script: Script
    screenplay_text: str = Field(..., description="Human-readable, formatted screenplay.")
    mode: str = Field(..., description="'llm' if generated by the model, 'mock' if using the sample fallback.")
